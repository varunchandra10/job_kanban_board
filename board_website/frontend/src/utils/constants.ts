export const getCountryName = (code?: string | null): string => {
  if (!code) return '';
  const trimmed = code.trim();
  if (trimmed.toUpperCase() === 'REMOTE') return 'Remote / Worldwide';
  const found = COUNTRIES.find(c => c.code.toUpperCase() === trimmed.toUpperCase());
  return found ? found.name : trimmed;
};

